const VALID_CATEGORIES = new Set([
  "ORDER",
  "PAYMENT",
  "DELIVERY",
  "INSTALLATION",
  "SUPPORT",
  "PROMOTION",
  "PRICE_ALERT",
  "SECURITY",
  "CUSTOMER",
  "PRODUCT",
  "INVENTORY",
]);

export function getNotificationDisplayCategory(notification = {}) {
  const category = String(notification.category || "").trim().toUpperCase();
  const type = String(notification.type || "").trim().toUpperCase();
  if (category !== "SYSTEM" && VALID_CATEGORIES.has(category)) return category;
  return CATEGORY_BY_TYPE[type] || (category === "SYSTEM" ? "SYSTEM" : "SYSTEM");
}

